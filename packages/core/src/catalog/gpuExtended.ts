import type { CatalogModel } from './models.ts';

function gpu(
  key: string,
  manufacturer: string,
  series: string,
  model: string,
  aliases: string[],
  typos: string[],
  demand: number,
  liquidity: number,
  gamingTags: string[],
  vramGb: number,
  memoryType: string,
  typicalBuildBand: string,
): CatalogModel {
  return {
    key,
    type: 'GPU',
    displayName: model,
    manufacturer,
    series,
    model,
    aliases,
    typos,
    demand,
    liquidity,
    gamingTags,
    vramGb,
    memoryType,
    typicalBuildBand,
  };
}

